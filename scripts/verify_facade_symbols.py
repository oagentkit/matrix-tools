def versions_org(versions_path: Path) -> str:
    """矩阵真相源里的 org。importPath 与钉定解析必须共用同一个前缀。"""
    data = json.loads(versions_path.read_text(encoding="utf-8"))
    return data.get("org") or data.get("defaultOrg", "oagentkit")


def facade_pins(gomod_text: str) -> dict[str, str]:
    """门面 go.mod 原文 → {module 路径: 钉定版本}。

    解析复用事实层 `matrix_facts.parse_go_mod`（只取事实，不含判定）——
    自己再写一份迟早与事实层分叉，分叉出来的就是盲区。
    indirect 的 require 也算钉定：MVS 里它同样参与选版。
    """
    out: dict[str, str] = {}
    for item in matrix_facts.parse_go_mod(gomod_text)["requires"]:
        path, ver = item.split(" ", 1)
        out[path] = ver
    return out


def resolve_pin_ref(pins: dict[str, str], org: str, repo: str,
                    import_path: str) -> "tuple[str | None, str | None]":
    """importPath → 对账它的 git ref（门面 go.mod 钉定版本对应的 tag）。

    → (ref, None)；解析不出 ⇒ (None, 原因)——调用方判红（fail-closed），不回落 main。

    匹配用 Go module 语义：importPath 命中的**最长 module 前缀**。
    ref 构造：顶层 module 钉 v ⇒ `v`；嵌套 module（`<top>/<子目录>`）钉 v ⇒
    `<子目录>/v`（嵌套 module 的 tag 带子目录前缀，与 repo_meta.nested_tag 同一约定）。
    """
    best = None
    for mod in pins:
        if (import_path == mod or import_path.startswith(mod + "/")) and (
                best is None or len(mod) > len(best)):
            best = mod
    if best is None:
        return None, (
            f"门面 go.mod 没钉住 {import_path} 所在的 module——"
            "按钉定版本对账判不了（fail-closed，不回落 main）")
    top = f"github.com/{org}/{repo}"
    if best == top:
        return pins[best], None
    if best.startswith(top + "/"):
        rel = best[len(top) + 1:]
        return f"{rel}/{pins[best]}", None
    return None, f"module {best} 不属于 github.com/{org}/{repo}——对账对象错位，判不了"


def resolve_repo_refs(pins: dict[str, str], facade_pkgs: list[str],
                      index: dict, org: str) -> "tuple[dict[str, str], dict[str, str], list[str]]":
    """门面转发的包 ⇒ 每个上游仓的钉定 ref。→ ({repo: ref}, {pkg: 口径注记}, problems)。

    两模式共用：联网与本地只有「快照从哪来」不同，ref 解析不许有两份实现。
    """
    problems: list[str] = []
    repo_ref: dict[str, str] = {}
    notes: dict[str, str] = {}
    for pkg in facade_pkgs:
        info = index.get(pkg)
        if info is None:
            # 矩阵漏登记：local_inputs 会报（幽灵包门禁负责），这里无从解析
            continue
        ref, why = resolve_pin_ref(pins, org, info["repo"], info["importPath"])
        if ref is None:
            problems.append(f"{pkg}: {why}")
            continue
        notes[pkg] = f"{info['repo']}@{ref}"
        prev = repo_ref.get(info["repo"])
        if prev is not None and prev != ref:
            problems.append(
                f"{info['repo']}: 同一个仓的包解析出两个钉定版本（{prev} vs {ref}）——判不了")
            continue
        repo_ref[info["repo"]] = ref
    return repo_ref, notes, problems


def _run_git(repo_dir: Path, *args: str) -> "tuple[bool, str]":
    proc = subprocess.run(["git", "-C", str(repo_dir), *args],
                          capture_output=True, text=True)
    return proc.returncode == 0, (proc.stderr or proc.stdout).strip()


def _git_snapshot(repo_dir: Path, ref: str, dest: Path) -> "tuple[Path | None, str | None]":
    """把本地 git 仓 ref 指向的树 archive 出来，解到 dest/<仓名>。

    → (解出的目录 | None, 取不到时的原因 | None)。

    为什么走 git archive 而不是拿工作区：工作区被检在哪个 ref，门禁不知道
    （CI 浅克隆检 main、本地可能检在任何提交上）——拿工作区当钉定版本对账，
    就会把「main 有、钉定版本没有」的符号判成门面漏转发（issue #201 实测形态）。

    tag 不在本地（浅克隆没带 tag 等）⇒ 先显式 shallow fetch 这**一个** tag
    再 archive（.github repo-ci 的浅克隆走的就是这条路）；仍取不到 ⇒
    (None, 原因)，由调用方判红——**不静默回落工作区**。
    """
    import io
    import tarfile

    ok, _ = _run_git(repo_dir, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}")
    if not ok:
        _run_git(repo_dir, "fetch", "--depth", "1", "origin",
                 f"+refs/tags/{ref}:refs/tags/{ref}")
        ok, err = _run_git(repo_dir, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}")
        if not ok:
            return None, (
                f"钉定版本 {ref} 检不出（本地仓无此 tag，shallow fetch 也失败："
                f"{err[:200] or '原因不明'}）")
    proc = subprocess.run(
        ["git", "-C", str(repo_dir), "archive", "--format=tar", ref],
        capture_output=True)
    if proc.returncode != 0 or not proc.stdout:
        err = (proc.stderr or b"").decode(errors="replace").strip()
        return None, f"git archive {ref} 失败：{err[:200] or '无输出'}"
    target = dest / repo_dir.name
    try:
        # git archive 的成员名**不带**仓根前缀（与 GitHub tarball 不同），直接是仓相对路径。
        # 解包只落普通文件：符号链接、硬链接、绝对路径、`..` 路径一律跳过。
        with tarfile.open(fileobj=io.BytesIO(proc.stdout), mode="r:") as tf:
            for m in tf.getmembers():
                if m.issym() or m.islnk():
                    continue
                rel = m.name
                if not rel or rel.startswith("/") or ".." in Path(rel).parts:
                    continue
                out = target / rel
                if m.isdir():
                    out.mkdir(parents=True, exist_ok=True)
                elif m.isfile():
                    out.parent.mkdir(parents=True, exist_ok=True)
                    src = tf.extractfile(m)
                    if src is not None:
                        out.write_bytes(src.read())
    except (tarfile.TarError, OSError, ValueError):
        return None, "git archive 产物解包失败"
    if not target.is_dir():
        return None, f"git archive {ref} 解出来没有内容"
    return target, None


def pinned_snapshots_local(root: Path, facade_dir: Path, index: dict, org: str,
                           work: Path) -> "tuple[Path | None, dict[str, str], list[str]]":
    """本地模式的上游快照：按门面 go.mod 钉定版本，从各仓 git object store 取。

    → (上游快照根 | None, {pkg: 口径注记}, problems)。problems 非空 ⇒ 调用方
    不出任何包级结论（fail-closed：对账口径立不住时，部分判定比不判定更误导）。
    """
    gomod = facade_dir / "go.mod"
    if not gomod.is_file():
        return None, {}, [
            f"读不到门面 go.mod（{gomod}）——钉定版本无从解析，判不了"
            "（fail-closed，不回落 main）"]
    pins = facade_pins(gomod.read_text(encoding="utf-8"))
    if not pins:
        return None, {}, [
            "门面 go.mod 里解析不出任何 require——钉定版本无从解析，判不了"
            "（fail-closed，不回落 main）"]
    # 门面实际转发的包：门面仓下一层含 alias.go 的目录（枚举基准同 local_inputs）。
    facade_pkgs = sorted(
        child.name for child in facade_dir.iterdir()
        if child.is_dir() and not child.name.startswith(".")
        and (child / "alias.go").is_file()
    )
    repo_ref, notes, problems = resolve_repo_refs(pins, facade_pkgs, index, org)
    for repo in sorted(repo_ref):
        ref = repo_ref[repo]
        src = root / repo
        if not src.is_dir():
            problems.append(
                f"{repo}: 本地没有该仓的检出（{src}）——取不到钉定版本 {ref} 的快照，判不了")
            continue
        got, why = _git_snapshot(src, ref, work)
        if got is None:
            problems.append(
                f"{repo}: 取不到钉定版本 {ref} 的源码快照（{why}）——按钉定版本对账判不了，"
                "不回落本地工作区（工作区可能检在 main 上，正是 issue #201 的坑）")
    if problems:
        return None, notes, problems
    return work, notes, []


# ---------------------------------------------------------------- 本地模式

def local_inputs(root: Path, facade_dir: Path, index: dict,
                 notes: "dict[str, str] | None" = None) -> tuple[list, list, list]:
    """构造 symdump 的 manifest（本地模式）。→ (manifest, 门面元信息, 问题)

    `notes`（pkg → "repo@ref"）是调用方解析出的**对账口径**：两种模式的调用方都会
    先把上游源码按门面 go.mod 钉定版本准备好再进来，这里只在报问题时报出口径，
    让「判不了」的人一眼看到当时按哪个版本对的账。

    # 枚举基准：门面**实际转发**的包，不是矩阵的全部包

    这条门禁的立论是「**已冻结的那张脸**有没有长歪」——门面转发了什么，就核对什么。
    枚举基准若取「矩阵的全部包」，矩阵每新增一个包，这条门禁就要求门面跟着长一张新脸；
    而门面早已废弃（「不接受任何新功能，只做别名转发」），**矩阵新增包时门面不该跟**。

    两条门禁各管一面、互不重叠：
    - 本门禁（符号级）：门面**已经转发**的包，符号集是否与上游对得上；
    - `verify_facade_frozen.py`（包级）：门面的**实际包集合**是否 ⊆ 冻结基线，
      即「门面有没有长出新包」。门面若多转发了 `toolfail`，冻结门禁会报红。

    所以「门面没转发某个矩阵包」**不是这条门禁的问题**——那是正常状态，不是缺陷。
    把它报红会让矩阵每次新增包都撞红，而修法（给门面补转发）恰恰是门面不该做的事。

    漏转发怎么仍然被抓住：门面的 alias.go 若转发了一个上游**已不存在的符号**，
    那是「幽灵转发」，由 `check_package` 报红；门面的 alias.go 若**漏了上游的某个符号**，
    那是「漏转发」，同样由 `check_package` 报红——两者都发生在「门面确实转发了的包」上，
    与枚举基准无关。
    """
    manifest = {"upstream": [], "facade": []}
    facade_meta = []
    problems: list[str] = []
    # 门面实际转发的包：门面仓下一层含 alias.go 的目录。
    facade_pkgs = sorted(
        child.name for child in facade_dir.iterdir()
        if child.is_dir() and not child.name.startswith(".")
        and (child / "alias.go").is_file()
    )
    for pkg in facade_pkgs:
        info = index.get(pkg)
        if info is None:
            # 门面转发的包不在矩阵登记里：矩阵漏登记，由幽灵包门禁负责；
            # 本门禁无从核对上游（拿不到 importPath），跳过而不误报。
            problems.append(f"{pkg}: 门面转发了它，但矩阵未登记该包（判不了上游符号）")
            continue
        up_dir = root / info["repo"] / info["subdir"] if info["subdir"] else root / info["repo"]
        alias = facade_dir / pkg / "alias.go"
        note = (notes or {}).get(pkg)
        if not up_dir.is_dir():
            problems.append(
                f"{pkg}: 上游包目录不存在（{up_dir}）"
                + (f"——按钉定版本 {note} 对账，该版本里没有这个包" if note else "")
                + "，判不了")
            continue
        manifest["upstream"].append({"key": pkg, "dir": str(up_dir.resolve())})
        manifest["facade"].append({"key": pkg, "file": str(alias.resolve())})
        facade_meta.append(pkg)
    return manifest, facade_meta, problems


# ---------------------------------------------------------------- 联网模式

def remote_inputs(org: str, facade_repo: str, index: dict) -> tuple[list, list, list, str | None]:
    """构造 symdump 的 manifest（联网模式）。

    先把源码快照拉到临时目录，再**复用本地模式那套检查逻辑**——
    联网与本地只有「源码从哪来」不同，判据不该有两份实现（两份实现迟早分叉，
    分叉出来的就是盲区）。

    对账 ref（issue #201）：门面快照取 **main**（门禁审的就是当前门面，
    而它 go.mod 里钉的上游版本就是已发布版本）；上游快照按**钉定 tag** 取
    （`fetch_repo_snapshot(..., ref=tag)`——此前不传 ref 默认拿 main，那是未发布
    快照，会要求门面转发它依赖里不存在的符号）。钉定解析不出 / tag 取不到 ⇒
    红（fail-closed），**不回落 main**。

    → (manifest, 门面元信息, 问题, 临时目录)
    """
    tmpdir = tempfile.mkdtemp(prefix="facade-syms-")
    root = Path(tmpdir)
    problems: list[str] = []

    if repo_meta.fetch_repo_snapshot(org, facade_repo, root) is None:
        return {"upstream": [], "facade": []}, [], [
            f"取不到 {org}/{facade_repo} 的源码快照（门面 go.mod 无从读起），判不了"], tmpdir
    facade_dir = root / facade_repo
    gomod = facade_dir / "go.mod"
    pins = facade_pins(gomod.read_text(encoding="utf-8")) if gomod.is_file() else {}
    if not pins:
        problems.append(
            f"{facade_repo} 快照里解析不出 go.mod require——钉定版本无从解析，"
            "判不了（fail-closed，不回落 main）")
    # 门面实际转发的包：枚举基准同 local_inputs（门面仓下一层含 alias.go 的目录）。
    facade_pkgs = sorted(
        child.name for child in facade_dir.iterdir()
        if child.is_dir() and not child.name.startswith(".")
        and (child / "alias.go").is_file()
    )
    repo_ref, notes, pin_problems = resolve_repo_refs(pins, facade_pkgs, index, org)
    problems += pin_problems
    for repo in sorted(repo_ref):
        ref = repo_ref[repo]
        if repo_meta.fetch_repo_snapshot(org, repo, root, ref=ref) is None:
            problems.append(
                f"取不到 {org}/{repo}@{ref} 的源码快照（tag 被删？）——"
                "按钉定版本对账判不了，不回落 main")
    if problems:
        return {"upstream": [], "facade": []}, [], problems, tmpdir

    manifest, facade_meta, local_problems = local_inputs(
        root, facade_dir, index, notes)
    return manifest, facade_meta, local_problems, tmpdir


# ---------------------------------------------------------------- 判定

def check_package(pkg: str, up: dict, fa: dict, matrix_import: str) -> list[str]:
    """单个门面包的问题描述列表（空 = 符号级完整）。

    up: {符号名: {"kind": ..., "generic": bool}}
    fa: {"upstream": 路径, "declared": {名: 转发kind}, "localDefs": [...], "docGenerics": [...]}
    """
    problems: list[str] = []
    declared = fa.get("declared", {})

    # 6. 门面转发到的上游包必须与矩阵登记的一致
    if fa.get("upstream") and matrix_import and fa["upstream"] != matrix_import:
        problems.append(
            f"{pkg}: 门面的 upstream import 是 {fa['upstream']}，"
            f"矩阵登记的 importPath 是 {matrix_import}——对账对象错了，"
            f"先修门面的转发路径")

    whitelist = GENERIC_FUNC_WHITELIST.get(pkg, set())
    up_generic_funcs = {n for n, s in up.items()
                        if s["kind"] == "func" and s.get("generic")}

    for name in sorted(up):
        sym = up[name]
        if sym["kind"] == "func" and sym.get("generic"):
            # 4. 泛型函数
            if name in declared:
                problems.append(
                    f"{pkg}: 泛型函数 {name} 被转发了——Go 不允许 `var F = pkg.F[T]`，"
                    f"必须删掉这条转发并让下游直接引用上游")
            if name not in whitelist:
                problems.append(
                    f"{pkg}: 上游新增泛型函数 {name}，未登记进 GENERIC_FUNC_WHITELIST——"
                    f"必须显式决定它怎么处理（泛型函数无法用变量别名转发）")
            continue
        if name not in declared:
            problems.append(
                f"{pkg}: 漏转发上游导出符号 {name}（上游 kind={sym['kind']}）")
            continue
        want, got = sym["kind"], declared[name]
        if want in ("type", "const") and got != want:
            if want == "type":
                why = ("type 被降级成 var 后门面自己就编译不过"
                       "（var 块里不能赋一个类型）")
            else:
                why = ("const 被降级成 var 后，下游把它用在**常量位置**会编译不过"
                       "（const 声明、数组长度等要求常量）"
                       "——注意：expression switch 的 case 不受此影响，"
                       "Go 规范允许 case 表达式不是常量")
            problems.append(
                f"{pkg}: {name} 转发 kind 错配——上游是 {want}，门面转发成 {got}；{why}")

    for name in sorted(declared):
        if name not in up:
            problems.append(
                f"{pkg}: 幽灵转发 {name}——上游已没有这个导出符号（陈旧转发）")

    # 7. 运行期可变 var 的门面别名必须带 // Deprecated: 标记（agentkit#166）。
    # 「运行期可变」的可判定代理 = 上游对同一符号导出了 setter（func Set<名>）：
    # setter 的存在说明该 var 的生效配置走 setter 路径，门面别名只是 init 期
    # 值拷贝——经门面对别名赋值/append 是死写（写门面副本，上游读自己的快照），
    # 编译过、运行静默失效。没有 Deprecated 标记 ⇒ 静态分析（gopls/staticcheck
    # SA1019/IDE 删除线）零信号，陷阱以「正常可用」姿态导出。
    deprecated = set(fa.get("deprecatedVars") or [])
    for name in sorted(declared):
        if declared[name] != "var":
            continue
        setter = f"Set{name}"
        if up.get(setter, {}).get("kind") == "func" and name not in deprecated:
            problems.append(
                f"{pkg}: {name} 别名缺 // Deprecated: 标记——上游有 setter "
                f"{setter}，别名是 init 期拷贝，经门面赋值是死写"
                "（agentkit#166：运行期可变 var 别名必须带标记退役）")

    # 4b. 白名单过期：登记为泛型函数的符号，上游已不是泛型函数了
    for name in sorted(whitelist):
        if name not in up_generic_funcs:
            problems.append(
                f"{pkg}: 白名单里的 {name} 在上游已经不是泛型函数——"
                f"白名单过期会掩盖真实状态，请同步更新 GENERIC_FUNC_WHITELIST")

    # 5. 文档里的泛型函数豁免清单必须与上游实际一致
    doc = set(fa.get("docGenerics") or [])
    if doc != up_generic_funcs:
        problems.append(
            f"{pkg}: 包文档声明的泛型函数豁免是 {sorted(doc) or '（无）'}，"
            f"上游实际的泛型函数是 {sorted(up_generic_funcs) or '（无）'}——"
            f"文档是门面对下游的公开承诺，漂了下游就不知道该直接引上游")

    # 门面是纯转发层：出现自研定义说明它不再是纯 re-export
    for name in sorted(fa.get("localDefs") or []):
        problems.append(
            f"{pkg}: 门面里出现了非转发定义 {name}——门面应当是纯 re-export 层，"
            f"自研逻辑请放回上游模块仓")

    return problems


# ---------------------------------------------------------------- 自测

def selftest() -> int:
    """oracle 有效性自测：拿一个**有盲区的被检对象**跑一遍，确认它报得出。

    这不是形式检查——如果 oracle 自己也有同一处盲区，它会对着坏对象说「没问题」，
    那门禁就是假通过。所以自测里故意造多类缺陷，逐一断言它被抓到；
    第九组（issue matrix-tools#201）用真实 git 仓造「对账口径」变异体：
    上游 main 有新符号而钉定版本没有时**必须绿**（修前必红）、
    钉定版本有而门面漏时**必须红**、钉定版本取不到时**必须红且不回落 main**。
    """
    failures: list[str] = []

    def check(name: str, got: bool, want: bool) -> None:
        if got != want:
            failures.append(f"{name}: got={got} want={want}")

    with tempfile.TemporaryDirectory() as td:
        root = Path(td) / "root"
        facade = Path(td) / "facade"
        (root / "up" / "pkg").mkdir(parents=True)
        (facade / "pkg").mkdir(parents=True)

        # 上游：1 func / 1 const / 1 type / 1 泛型函数 / 1 泛型类型
        (root / "up" / "pkg" / "a.go").write_text(
            "package pkg\n\n"
            "const Bar = 1\n\n"
            "type Baz struct{}\n\n"
            "type Gen[T any] struct{ V T }\n\n"
            "func Foo() {}\n\n"
            "func GenFn[T any](v T) T { return v }\n",
            encoding="utf-8")
        # 门面：只转发 Foo；漏 Bar / Baz / Gen；幽灵 Qux；泛型函数 GenFn 被错误转发
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            "\tQux = upstream.Qux\n"
            "\tGenFn = upstream.GenFn\n"
            ")\n",
            encoding="utf-8")

        manifest = {
            "upstream": [{"key": "pkg", "dir": str(root / "up" / "pkg")}],
            "facade": [{"key": "pkg", "file": str(facade / "pkg" / "alias.go")}],
        }
        out = run_symdump(manifest)
        up = out["upstream"]["pkg"]["symbols"]
        fa = out["facade"]["pkg"]

        check("上游符号提取：Bar 认成 const", up.get("Bar", {}).get("kind") == "const", True)
        check("上游符号提取：Baz 认成 type", up.get("Baz", {}).get("kind") == "type", True)
        check("上游符号提取：Foo 认成 func", up.get("Foo", {}).get("kind") == "func", True)
        check("上游符号提取：泛型类型 Gen 被标 generic",
              up.get("Gen", {}).get("generic") is True, True)
        check("上游符号提取：泛型函数 GenFn 被标 generic",
              up.get("GenFn", {}).get("generic") is True, True)
        check("上游符号提取：非泛型符号不带 generic",
              up.get("Foo", {}).get("generic") is False, True)

        problems = check_package("pkg", up, fa, "github.com/up/pkg")
        joined = "\n".join(problems)
        check("漏转发被报出：Bar", "漏转发上游导出符号 Bar" in joined, True)
        check("漏转发被报出：Baz", "漏转发上游导出符号 Baz" in joined, True)
        check("幽灵转发被报出：Qux", "幽灵转发 Qux" in joined, True)
        check("泛型函数被转发被报出", "泛型函数 GenFn 被转发了" in joined, True)
        check("白名单外的泛型函数被报出", "未登记进 GENERIC_FUNC_WHITELIST" in joined, True)
        check("泛型类型 Gen 被报成缺失（泛型类型必须转发，不豁免）",
              "漏转发上游导出符号 Gen" in joined, True)
        check("泛型函数 GenFn 未被误报成缺失",
              "漏转发上游导出符号 GenFn" in joined, False)

        # 第三组：agentkit#166 规则——上游有 setter 的 var，门面别名缺
        # 规则：上游有 setter 的 var，门面别名缺 // Deprecated: 标记必须判红；带了标记不误报。
        (root / "up" / "pkg" / "b.go").write_text(
            "package pkg\n\n"
            "var Table = []int{1, 2}\n\n"
            "func SetTable(t []int) { Table = t }\n",
            encoding="utf-8")
        (facade / "pkg" / "b.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tTable = upstream.Table\n"
            ")\n",
            encoding="utf-8")
        out2 = run_symdump({
            "upstream": [{"key": "pkg", "dir": str(root / "up" / "pkg")}],
            "facade": [{"key": "pkg", "file": str(facade / "pkg" / "b.go")}],
        })
        fa2 = out2["facade"]["pkg"]
        problems2 = check_package("pkg", out2["upstream"]["pkg"]["symbols"], fa2,
                                  "github.com/up/pkg")
        joined2 = "\n".join(problems2)
        check("缺 Deprecated 标记被报出（上游有 setter 的 var 别名）",
              "Table 别名缺 // Deprecated: 标记" in joined2, True)
        check("symdump 提取到该别名未带标记", fa2.get("deprecatedVars") == [], True)

        # 正向：同一别名带 // Deprecated: 标记 ⇒ 不报，且 symdump 收进 deprecatedVars
        (facade / "pkg" / "b.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\t// Deprecated: use SetTable instead.\n"
            "\tTable = upstream.Table\n"
            ")\n",
            encoding="utf-8")
        out3 = run_symdump({
            "upstream": [{"key": "pkg", "dir": str(root / "up" / "pkg")}],
            "facade": [{"key": "pkg", "file": str(facade / "pkg" / "b.go")}],
        })
        fa3 = out3["facade"]["pkg"]
        problems3 = check_package("pkg", out3["upstream"]["pkg"]["symbols"], fa3,
                                  "github.com/up/pkg")
        joined3 = "\n".join(problems3)
        check("带 Deprecated 标记不误报", "缺 // Deprecated" in joined3, False)
        check("symdump 收进 deprecatedVars", fa3.get("deprecatedVars"), ["Table"])

        # 第二组：const 转发进 var 块 → 必须报 kind 错配
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            "\tBar = upstream.Bar\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        problems = check_package("pkg", up, fa, "github.com/up/pkg")
        check("const 转发成 var 被报出错配",
              "Bar 转发 kind 错配" in "\n".join(problems), True)

        # 第三组：type 转发成 var 也必须报出
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tBaz = upstream.Baz\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        check("type 转发成 var 被报出错配",
              "Baz 转发 kind 错配" in "\n".join(check_package("pkg", up, fa, "github.com/up/pkg")),
              True)

        # 第四组：泛型类型必须用 type 块转发（var 块转发泛型类型 = 下游用不了）
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tGen = upstream.Gen\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        check("泛型类型转发成 var 被报出错配",
              "Gen 转发 kind 错配" in "\n".join(check_package("pkg", up, fa, "github.com/up/pkg")),
              True)

        # 第五组：完整转发（泛型类型用 type 块）→ 不该报「不漏/错配/幽灵」
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "type (\n"
            "\tBaz = upstream.Baz\n"
            "\tGen[T any] = upstream.Gen[T]\n"
            ")\n\n"
            "const (\n"
            "\tBar = upstream.Bar\n"
            ")\n\n"
            "var (\n"
            "\tFoo = upstream.Foo\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        problems = check_package("pkg", up, fa, "github.com/up/pkg")
        check("完整转发不报不漏/错配/幽灵",
              not any(("漏转发" in p or "kind 错配" in p or "幽灵转发" in p) for p in problems),
              True)

        # 第七组：文档里的泛型函数清单与上游实际不一致 → 必须报出
        (facade / "pkg" / "alias.go").write_text(
            "// Package pkg 是兼容门面。\n"
            "//\n"
            "// 注意：泛型函数无法用变量别名转发，这些符号请直接引用上游：GenFn\n"
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        check("文档泛型清单被解析出来", fa.get("docGenerics") == ["GenFn"], True)

        # 第八组：白名单**命中**与**过期**两条路径
        #
        # 这两条必须分开测：白名单命中时（上游确有该泛型函数、门面也没转发）
        # 不该报错；白名单过期时（上游已没有那个泛型函数）必须报错。
        # 只测一条的话，另一条坏了门禁照样绿。
        for pkg_name, upstream_src, want_stale in (
            ("hotplug", "func NewHolder[T any](v T) T { return v }\n", False),
            ("progress", "func Plain() {}\n", True),
        ):
            up_dir = root / "wl" / pkg_name
            up_dir.mkdir(parents=True, exist_ok=True)
            (up_dir / "a.go").write_text(
                f"package {pkg_name}\n\n" + upstream_src, encoding="utf-8")
            fa_dir = facade / pkg_name
            fa_dir.mkdir(parents=True, exist_ok=True)
            (fa_dir / "alias.go").write_text(
                f"package {pkg_name}\n\n"
                f'import upstream "github.com/up/{pkg_name}"\n\n'
                "var (\n"
                "\tPlain = upstream.Plain\n"
                ")\n",
                encoding="utf-8")
            wl_manifest = {
                "upstream": [{"key": pkg_name, "dir": str(up_dir)}],
                "facade": [{"key": pkg_name, "file": str(fa_dir / "alias.go")}],
            }
            wl_out = run_symdump(wl_manifest)
            wl_problems = check_package(
                pkg_name, wl_out["upstream"][pkg_name]["symbols"],
                wl_out["facade"][pkg_name], f"github.com/up/{pkg_name}")
            wl_joined = "\n".join(wl_problems)
            if want_stale:
                check(f"白名单过期（{pkg_name}）被报出",
                      "白名单过期" in wl_joined, True)
            else:
                check(f"白名单命中（{pkg_name}）不报过期",
                      "白名单过期" in wl_joined, False)
                check(f"白名单命中（{pkg_name}）不报未登记",
                      "未登记进 GENERIC_FUNC_WHITELIST" in wl_joined, False)
                check(f"白名单命中（{pkg_name}）的泛型函数不算漏转发",
                      "漏转发" in wl_joined, False)

    # 第九组：对账口径变异体（issue matrix-tools#201）
    #
    # 真实 git 仓做夹具（全程离线）：上游 v0.1.0 tag = {Foo, Bar}；main 在 tag
    # 之后新增 NewThing。门面 go.mod 钉 v0.1.0，alias.go 转发 v0.1.0 的全部符号。
    #   变异体 A（修前必红，修后必须绿）：main 有 NewThing 而钉定版本没有
    #     ⇒ 门禁**不得**要求门面转发 NewThing——转发它门面编译不过
    #       （钉定版本的 upstream 里没这个符号），正是 issue #201 实测的破坏性修法。
    #   变异体 B（反向仍红）：钉定版本有 Bar 而门面漏 ⇒ 仍判红（口径不能变松）。
    #   变异体 C（fail-closed）：钉定版本取不到 ⇒ 判红并说明，不出包级结论，
    #     **不许**静默拿 main/工作区内容充数。
    def _git(cwd: Path, *args: str) -> None:
        proc = subprocess.run(["git", "-C", str(cwd), *args],
                              capture_output=True, text=True)
        if proc.returncode != 0:
            failures.append(
                f"git 夹具 {' '.join(args[:2])} 失败: {proc.stderr.strip()[:200]}")

    with tempfile.TemporaryDirectory() as gd:
        g_root = Path(gd) / "root"
        g_facade = Path(gd) / "facade"
        up = g_root / "gup"
        (up / "pkg").mkdir(parents=True)
        (up / "pkg" / "a.go").write_text(
            "package pkg\n\nconst Bar = 1\n\nfunc Foo() {}\n", encoding="utf-8")
        _git(up, "init", "-q", "-b", "main")
        _git(up, "add", "-A")
        _git(up, "-c", "user.name=t", "-c", "user.email=t@example.com",
             "commit", "-q", "-m", "init")
        _git(up, "tag", "v0.1.0")
        (up / "pkg" / "a.go").write_text(
            "package pkg\n\nconst Bar = 1\n\nconst NewThing = 2\n\nfunc Foo() {}\n",
            encoding="utf-8")
        _git(up, "add", "-A")
        _git(up, "-c", "user.name=t", "-c", "user.email=t@example.com",
             "commit", "-q", "-m", "add NewThing on main（不发包）")

        (g_facade / "pkg").mkdir(parents=True)
        (g_facade / "go.mod").write_text(
            "module github.com/oagentkit/agentkit\n\ngo 1.26\n\n"
            "require github.com/oagentkit/gup v0.1.0\n", encoding="utf-8")

        # 钉定解析的单元变异体
        g_pins = facade_pins((g_facade / "go.mod").read_text(encoding="utf-8"))
        check("go.mod require 解析出钉定版本",
              g_pins, {"github.com/oagentkit/gup": "v0.1.0"})
        g_ref, g_why = resolve_pin_ref(
            g_pins, "oagentkit", "gup", "github.com/oagentkit/gup/pkg")
        check("顶层 module 命中 ⇒ ref=钉定 tag", (g_ref, g_why), ("v0.1.0", None))
        g_nested = dict(g_pins)
        g_nested["github.com/oagentkit/gup/sub"] = "v0.2.0"
        check("嵌套 module 命中 ⇒ ref=子目录前缀 tag",
              resolve_pin_ref(g_nested, "oagentkit", "gup",
                              "github.com/oagentkit/gup/sub/x")[0],
              "sub/v0.2.0")
        g_miss = resolve_pin_ref(g_pins, "oagentkit", "other", "github.com/oagentkit/other/x")
        check("go.mod 没钉的 module 解析不出 ref（fail-closed）",
              (g_miss[0] is None, bool(g_miss[1])), (True, True))

        g_index = {"pkg": {"repo": "gup", "subdir": "pkg",
                           "importPath": "github.com/oagentkit/gup/pkg"}}

        # 门面转发 v0.1.0 的全部符号（钉定版本里有的都转发了 ⇒ 对账应绿）
        (g_facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/oagentkit/gup/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            ")\n\n"
            "const (\n"
            "\tBar = upstream.Bar\n"
            ")\n", encoding="utf-8")

        # 变异体 A：快照必须取自钉定 tag，而不是检在 main 上的工作区
        g_work = Path(gd) / "work"
        up_root_a, notes_a, probs_a = pinned_snapshots_local(
            g_root, g_facade, g_index, "oagentkit", g_work)
        check("钉定快照取自 tag（解析无问题）", probs_a, [])
        check("口径注记带上 repo@tag", notes_a, {"pkg": "gup@v0.1.0"})
        check("工作区确实检在 main（NewThing 在场，证明 A 不是巧合）",
              "NewThing" in (up / "pkg" / "a.go").read_text(encoding="utf-8"), True)
        check("快照内容来自 v0.1.0（不含 main 的 NewThing）",
              "NewThing" in (up_root_a / "gup" / "pkg" / "a.go").read_text(encoding="utf-8"),
              False)

        g_manifest_a, _, g_local_a = local_inputs(up_root_a, g_facade, g_index, notes_a)
        check("变异体 A：按钉定版本枚举无额外问题", g_local_a, [])
        g_out_a = run_symdump(g_manifest_a)
        g_problems_a = check_package(
            "pkg", g_out_a["upstream"]["pkg"]["symbols"], g_out_a["facade"]["pkg"],
            "github.com/oagentkit/gup/pkg")
        check("变异体 A：main 新增符号不要求门面转发（修前必红，修后必须绿）",
              "NewThing" in "\n".join(g_problems_a), False)
        check("变异体 A：钉定版本符号齐全 ⇒ 门禁绿", g_problems_a, [])

        # 变异体 B：钉定版本有 Bar、门面漏 ⇒ 仍判红
        (g_facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/oagentkit/gup/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            ")\n", encoding="utf-8")
        g_manifest_b, _, _ = local_inputs(up_root_a, g_facade, g_index, notes_a)
        g_out_b = run_symdump(g_manifest_b)
        g_problems_b = check_package(
            "pkg", g_out_b["upstream"]["pkg"]["symbols"], g_out_b["facade"]["pkg"],
            "github.com/oagentkit/gup/pkg")
        check("变异体 B：钉定版本有而门面漏 ⇒ 仍判红",
              "漏转发上游导出符号 Bar" in "\n".join(g_problems_b), True)

        # 变异体 C：钉定版本取不到 ⇒ 红 + fail-closed 说明，不出包级结论
        (g_facade / "go.mod").write_text(
            "module github.com/oagentkit/agentkit\n\ngo 1.26\n\n"
            "require github.com/oagentkit/gup v9.9.9\n", encoding="utf-8")
        up_root_c, _, probs_c = pinned_snapshots_local(
            g_root, g_facade, g_index, "oagentkit", Path(gd) / "work-c")
        check("变异体 C：钉定 tag 取不到 ⇒ 判红", len(probs_c) > 0, True)
        check("变异体 C：红里说明不回落工作区/main",
              any("不回落" in p for p in probs_c), True)
        check("变异体 C：不出包级结论（快照根为 None）", up_root_c is None, True)

    if failures:
        print("❌ 自测失败：")
        for f in failures:
            print(f"   - {f}")
        return 1
    print("✅ 自测通过：漏转发 / 幽灵转发 / const 降级 / type 降级 / 泛型函数误转发 / "
          "泛型函数未登记白名单 / 白名单过期 / 泛型类型不误报 / "
          "钉定版本口径（main 新符号不要求转发 / 钉定版本漏转发仍红 / "
          "钉定取不到 fail-closed）全部按预期")
    return 0


# ---------------------------------------------------------------- 入口

def main() -> int:
    ap = argparse.ArgumentParser(description="校验门面的符号级 re-export 完整性")
    ap.add_argument("--facade", help="门面仓路径（agentkit 仓根）")
    ap.add_argument("--facade-repo", default="agentkit",
                    help="联网模式下的门面仓名（默认 agentkit）")
    ap.add_argument("--root", help="本地各仓父目录（含 agentkit 门面仓）")
    ap.add_argument("--org", help="联网模式：GitHub 组织名，如 oagentkit")
    ap.add_argument("--versions", default=str(DEFAULT_VERSIONS),
                    help="矩阵真相源 versions.json（提供 importPath 交叉校验）")
    ap.add_argument("--json", action="store_true", help="机器可读输出")
    ap.add_argument("--selftest", action="store_true", help="只跑 oracle 有效性自测")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    versions_path = Path(args.versions)
    if not versions_path.is_file():
        print(f"❌ 找不到矩阵文件: {versions_path}", file=sys.stderr)
        return 2
    index = matrix_index(versions_path)
    if not index:
        print(f"❌ {versions_path} 里没有可用的包清单", file=sys.stderr)
        return 2

    problems: list[str] = []
    checked = 0
    tmpdirs: list[str] = []
    if args.root:
        if not args.facade:
            print("本地模式必须给 --facade（门面仓路径）", file=sys.stderr)
            return 2
        facade_dir = Path(args.facade).resolve()
        root = Path(args.root).resolve()
        if not facade_dir.is_dir():
            print(f"❌ 门面仓路径不存在：{facade_dir}", file=sys.stderr)
            return 2
        org = args.org or versions_org(versions_path)
        work = tempfile.mkdtemp(prefix="facade-syms-pins-")
        tmpdirs.append(work)
        up_root, notes, problems = pinned_snapshots_local(
            root, facade_dir, index, org, Path(work))
        mode = f"local root={root} facade={facade_dir} 口径=门面 go.mod 钉住的版本"
        if up_root is not None:
            manifest, facade_meta, local_problems = local_inputs(
                up_root, facade_dir, index, notes)
            problems += local_problems
        else:
            # 对账口径立不住（fail-closed）：不出任何包级结论，problems 在下面原样报出。
            manifest, facade_meta = {"upstream": [], "facade": []}, []
    elif args.org:
        manifest, facade_meta, problems, tmpdir = remote_inputs(
            args.org, args.facade_repo, index)
        if tmpdir:
            tmpdirs.append(tmpdir)
        mode = f"remote org={args.org} facade={args.facade_repo} 口径=门面 go.mod 钉住的版本"
    else:
        print("必须给 --root（本地各仓父目录）或 --org（联网读）", file=sys.stderr)
        return 2

    try:
        out = run_symdump(manifest)
    except SymdumpError as e:
        print(f"❌ 符号提取失败（判不了，不能当成「没问题」）：{e}", file=sys.stderr)
        return 1
    finally:
        import shutil
        for td in tmpdirs:
            shutil.rmtree(td, ignore_errors=True)

    for pkg in facade_meta:
        up = out["upstream"].get(pkg, {})
        fa = out["facade"].get(pkg, {})
        if up.get("error"):
            problems.append(f"{pkg}: 上游符号提取失败：{up['error']}")
            continue
        if fa.get("error"):
            problems.append(f"{pkg}: 门面 alias.go 解析失败：{fa['error']}")
            continue
        problems += check_package(pkg, up.get("symbols", {}), fa,
                                  index[pkg]["importPath"])
        checked += 1

    if checked == 0:
        # 一个包都没查到 = 取数层坏了，不是「一致」。
        # 必须把取数层报的原因一并打出来，否则只看到「没检查到」，
        # 排查的人会以为是判据写错，而真因（API 取不到 / 路径不对）在上面。
        print("❌ 一个门面包都没检查到（拒绝判定）", file=sys.stderr)
        for p in problems:
            print(f"   - {p}", file=sys.stderr)
        if not problems:
            print("   （取数层没有报出具体原因——检查 matrix 的 importPath 与仓库布局是否对得上）",
                  file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps({
            "mode": mode,
            "checked_packages": checked,
            "problems": problems,
        }, ensure_ascii=False, indent=2))
        return 1 if problems else 0

    if not problems:
        print(f"✅ 门面符号级转发完整（{mode}，核对 {checked} 个包）")
        return 0

    print(f"❌ 门面符号级转发不完整（{mode}，核对 {checked} 个包）：")
    for p in problems:
        print(f"   - {p}")
    print()
    print("修法：")
    print("  1) 漏转发 → 在对应门的 alias.go 里补上别名")
    print("     （对账口径是门面 go.mod 钉住的版本：该符号在门面的依赖里真实存在，补上即可编译）")
    print("     type 上游 → type 块；const 上游 → const 块；func/var 上游 → var 块")
    print("  2) kind 错配 → 把该条目从 var 块挪到 type/const 块")
    print("  3) 幽灵转发 → 删掉该别名（钉定版本已无此符号）")
    print("  4) 泛型函数 → 不要转发，让下游直接引用上游；并登记进 GENERIC_FUNC_WHITELIST")
    print("  5) 文档清单 → 与上游实际泛型函数保持一致")
    print("  6) 上游 main 新增、钉定版本还没有的符号**不**要求转发——")
    print("     等上游发版、门面 go.mod 抬钉之后自然进入对账口径（issue matrix-tools#201）")
    return 1


if __name__ == "__main__":
    sys.exit(main())
