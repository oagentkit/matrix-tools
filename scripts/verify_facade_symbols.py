#!/usr/bin/env python3
"""门面的**符号级**转发完整性校验。

## 为什么要有这条守卫

门面仓 `oagentkit/agentkit` 把各模块仓的包做别名转发，让下游**只需改 import 前缀、
无需改调用点**。已有的三条门面守卫查的都不是符号级：

| 守卫 | 查什么 | 查不到什么 |
|---|---|---|
| `verify_facade_packages.py` | 包名（47/47 通过） | 包内的**符号** |
| `check_facade_imports.py` | 禁用的 import 前缀 | 转发内容 |
| `verify_facade_release.py` | 版本地板 | 转发内容 |

实测 2026-10-20（本守卫落地前）：47 个门面包里，**3 个包漏转发 23 个上游导出符号**，
**另有 131 处上游 `const` 被门面转发成 `var`**。

- 漏转发 → 下游按门面 import 直接编译失败（`undefined: Rule` / `undefined: Tokens`）。
- const 降级成 var → 下游写 `switch op { case policy.OpToolCall: }` 编译不过
  （case 要求常量表达式）。这不是风格问题。

而 47 个 `alias.go` 的头部都写着 `// Code generated by gen. DO NOT EDIT.`——
**但 `gen` 这个生成器在仓库里根本不存在**。这行声明让人以为有生成器兜底、不会漂移，
实际这些文件是手工冻结的产物（已在 agentkit#12 一并改成实话）。
**本守卫就是那个"生成器"该做但没做的事**——它不生成任何东西，只对账。

## 判据

对门面的每个包（47 个）：

1. **不漏**：上游包导出的每个符号，门面都要有对应别名
2. **不错配**：上游是 `type` / `const` 的，门面必须用 `type` / `const` 块转发
   （上游是 `func` 的用 `var` 块转发是**正常**的——Go 允许 `var F = pkg.F`，
   调用点无差别；只有 type/const 降级成 var 才会破坏下游用法）
3. **不幽灵**：门面不得转发上游已不存在的符号（那是陈旧转发，指向已退役的 API）
4. **泛型函数豁免**：Go 的泛型函数**不能**用变量别名转发（`var F = pkg.F[T]` 不合法），
   所以上游的导出泛型函数必须**不转发**，并由下游直接引用上游

## 为什么用正则而不是 go/parser

本守卫是**独立 oracle**，判据不能复用任何被检对象的逻辑。门面的 alias.go 是
**手工维护**的（没有生成器），所以不存在"门禁复用生成器输出"的循环风险；
而判据本身用与生成器不同的技术实现（Python 正则 vs Go AST），
两套实现互为交叉验证——任一方的解析盲区都会被另一方照出来。

⚠️ 实测坑：**不要用 `go doc -all` 提取符号**——块内 `const` 与部分 `type` 抓不到。
`go doc` 只能抓出 19 个真实缺失符号，`go/parser` 才能抓准 23 个。
本脚本用正则直扫源文件，块内声明也能抓到。

## 用法

    verify_facade_symbols.py --facade <门面仓路径> --root <各仓父目录>
    verify_facade_symbols.py --facade <门面仓路径> --org oagentkit
    verify_facade_symbols.py --facade <门面仓路径> --root <各仓父目录> --json
    verify_facade_symbols.py --selftest

退出码: 0 = 符号级完整；1 = 有缺失/错配/幽灵转发；2 = 用法或环境错误。
"""

