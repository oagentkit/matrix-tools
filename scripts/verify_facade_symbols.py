# ---------------------------------------------------------------- Go 源码扫描

_LINE_COMMENT = re.compile(r"//[^\n]*")
_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.S)
_RAW_STRING = re.compile(r"`[^`]*`")
_INTERP_STRING = re.compile(r'"(?:\\.|[^"\\\n])*"')

# 顶层声明（列 0 开始）。方法 `func (r T) Name(` 单独排除。
_RE_FUNC = re.compile(r"^func\s+([A-Z]\w*)\s*[\(\[]", re.M)
_RE_FUNC_GENERIC = re.compile(r"^func\s+([A-Z]\w*)\s*\[", re.M)
_RE_METHOD = re.compile(r"^func\s*\(", re.M)
_RE_TYPE = re.compile(r"^type\s+([A-Z]\w*)\b", re.M)
_RE_VAR = re.compile(r"^var\s+([A-Z]\w*)\b", re.M)
_RE_CONST = re.compile(r"^const\s+([A-Z]\w*)\b", re.M)
_RE_BLOCK_OPEN = re.compile(r"^(var|const|type)\s*\(", re.M)
_RE_BLOCK_ENTRY = re.compile(r"^\t([A-Z]\w*)\b", re.M)

_ALIAS_IMPORT_RE = re.compile(r'import\s+upstream\s+"(?P<path>[^"]+)"')


def strip_noise(src: str) -> str:
    """去掉注释与字符串字面量，避免它们里的关键字被当成声明。

    字符串先于注释处理会产生误伤（`"http://x"` 里的 `//`），所以先把字符串整体换成
    占位符，再去注释。
    """
    src = _RAW_STRING.sub("``", src)
    src = _INTERP_STRING.sub('""', src)
    src = _BLOCK_COMMENT.sub("", src)
    src = _LINE_COMMENT.sub("", src)
    return src


def scan_go(src: str) -> tuple[dict[str, str], set[str]]:
    """扫一个 Go 源文件 → (导出符号名 → kind, 导出泛型函数名集合)

    kind ∈ {type, const, var, func}。
    """
    clean = strip_noise(src)
    symbols: dict[str, str] = {}
    generics: set[str] = set()

    # 泛型函数先摘出来：它们的声明形如 `func Name[T any](`，与普通 func 同一行。
    for m in _RE_FUNC_GENERIC.finditer(clean):
        generics.add(m.group(1))
    for m in _RE_FUNC.finditer(clean):
        if m.group(1) not in generics:
            symbols[m.group(1)] = "func"
    for m in _RE_METHOD.finditer(clean):
        pass  # 方法不进符号集：门面不转发方法
    for m in _RE_TYPE.finditer(clean):
        symbols.setdefault(m.group(1), "type")
    for m in _RE_VAR.finditer(clean):
        symbols.setdefault(m.group(1), "var")
    for m in _RE_CONST.finditer(clean):
        symbols.setdefault(m.group(1), "const")

    # 块形式：var ( ... ) / const ( ... ) / type ( ... )
    lines = clean.split("\n")
    i = 0
    while i < len(lines):
        m = _RE_BLOCK_OPEN.match(lines[i])
        if not m:
            i += 1
            continue
        kind = m.group(1)
        i += 1
        while i < len(lines) and lines[i].strip() != ")":
            em = _RE_BLOCK_ENTRY.match(lines[i])
            if em:
                name = em.group(1)
                symbols.setdefault(name, kind)
                if kind == "type" and "[" in lines[i].split("=")[0]:
                    pass  # 泛型类型别名：转发合法，不需要豁免
            i += 1
        i += 1
    return symbols, generics


def scan_dir(path: Path) -> tuple[dict[str, str], set[str]]:
    """扫一个包目录下的全部非测试 .go 文件。"""
    symbols: dict[str, str] = {}
    generics: set[str] = set()
    if not path.is_dir():
        return symbols, generics
    for f in sorted(path.iterdir()):
        if not f.is_file() or f.suffix != ".go" or f.name.endswith("_test.go"):
            continue
        s, g = scan_go(f.read_text(encoding="utf-8", errors="replace"))
        for k, v in s.items():
            symbols.setdefault(k, v)
        generics |= g
    return symbols, generics


def scan_remote(org: str, repo: str, pkg_path: str | None) -> tuple[dict[str, str], set[str]]:
    """联网取某包的符号。pkg_path 为 None 表示仓根即包。"""
    paths = _cached_tree(org, repo)
    if paths is None:
        return {}, set()
    prefix = "" if not pkg_path else pkg_path.rstrip("/") + "/"
    symbols: dict[str, str] = {}
    generics: set[str] = set()
    for p in paths:
        if not p.startswith(prefix) or not p.endswith(".go") or p.endswith("_test.go"):
            continue
        rel = p[len(prefix):]
        if "/" in rel:  # 只看该包目录的第一层
            continue
        text = _cached_file(org, repo, p)
        if text is None:
            return {}, set()
        s, g = scan_go(text)
        for k, v in s.items():
            symbols.setdefault(k, v)
        generics |= g
    return symbols, generics


# GitHub API 取数缓存：47 个门面包会重复拉同一个仓的树与文件，不缓存就是几十倍请求。
_TREE_CACHE: dict[tuple[str, str], list[str] | None] = {}
_FILE_CACHE: dict[tuple[str, str, str], str | None] = {}


def _cached_tree(org: str, repo: str) -> list[str] | None:
    key = (org, repo)
    if key not in _TREE_CACHE:
        _TREE_CACHE[key] = repo_meta.fetch_tree_paths(org, repo)
    return _TREE_CACHE[key]


def _cached_file(org: str, repo: str, path: str) -> str | None:
    key = (org, repo, path)
    if key not in _FILE_CACHE:
        _FILE_CACHE[key] = repo_meta.fetch_file(org, repo, path)
    return _FILE_CACHE[key]


# ---------------------------------------------------------------- 门面侧

def facade_packages(facade_dir: Path) -> list[tuple[str, str]]:
    """门面的 (包名, alias.go 源码) 列表（本地模式）。"""
    out = []
    if not facade_dir.is_dir():
        return out
    for d in sorted(facade_dir.iterdir()):
        if not d.is_dir() or d.name.startswith((".", "_")):
            continue
        a = d / "alias.go"
        if a.is_file():
            out.append((d.name, a.read_text(encoding="utf-8")))
    return out


def facade_packages_remote(org: str, repo: str) -> list[tuple[str, str]] | None:
    """联网取门面的 (包名, alias.go 源码) 列表。取不到返回 None（判不了）。"""
    paths = _cached_tree(org, repo)
    if paths is None:
        return None
    out = []
    for p in paths:
        if not p.endswith("/alias.go"):
            continue
        pkg = p.split("/")[0]
        if pkg.startswith((".", "_")):
            continue
        text = _cached_file(org, repo, p)
        if text is None:
            return None
        out.append((pkg, text))
    return sorted(out)


def facade_declared(alias_src: str) -> dict[str, str]:
    """门面 alias.go 里声明的符号 → 转发用的 kind。

    转发用的 kind 取决于它落在哪个块里：`type (...)` → type，`const (...)` → const，
    `var (...)` → var。`var X = upstream.X` 对函数是合法的，所以 func 上游用 var 转发
    不会在这里被标成错配。
    """
    clean = strip_noise(alias_src)
    declared: dict[str, str] = {}
    lines = clean.split("\n")
    i = 0
    while i < len(lines):
        m = _RE_BLOCK_OPEN.match(lines[i])
        if not m:
            i += 1
            continue
        kind = m.group(1)
        i += 1
        while i < len(lines) and lines[i].strip() != ")":
            em = _RE_BLOCK_ENTRY.match(lines[i])
            if em:
                declared.setdefault(em.group(1), kind)
            i += 1
        i += 1
    return declared


def upstream_target(import_path: str, org: str) -> tuple[str, str | None]:
    """从门面的 upstream import 路径反推 (仓名, 包内路径)。

    `github.com/oagentkit/textx/textutil` → ("textx", "textutil")
    `github.com/oagentkit/llm`           → ("llm", None)  # 仓根即包
    """
    rel = import_path
    prefix = f"github.com/{org}/"
    if rel.startswith(prefix):
        rel = rel[len(prefix):]
    parts = rel.split("/")
    repo = parts[0]
    pkg = "/".join(parts[1:]) or None
    return repo, pkg


# ---------------------------------------------------------------- 判定

def check_package(pkg: str, up_symbols: dict[str, str],
                  up_generics: set[str], declared: dict[str, str]) -> list[str]:
    """单个门面包的问题描述列表（空 = 符号级完整）。"""
    problems: list[str] = []

    # 泛型函数单独判：它们无法用变量别名转发，必须**不转发**。
    # 注意泛型函数不在 up_symbols 里（它的声明形如 `func Name[T any](`），
    # 所以必须单独遍历 up_generics，否则这处检查会被整个跳过。
    for name in sorted(up_generics):
        if name in declared:
            problems.append(
                f"{pkg}: 泛型函数 {name} 被转发了——Go 不允许 `var F = pkg.F[T]`，"
                f"必须删掉这条转发并让下游直接引用上游")

    for name in sorted(up_symbols):
        if name in up_generics:
            continue
        if name not in declared:
            problems.append(f"{pkg}: 漏转发上游导出符号 {name}（上游 kind={up_symbols[name]}）")
            continue
        want = up_symbols[name]
        got = declared[name]
        if want in ("type", "const") and got != want:
            why = ("type 被降级成 var 后，下游不能拿它当类型用"
                   if want == "type" else
                   "const 被降级成 var 后，下游 `case` 分支用不了（case 要求常量表达式）")
            problems.append(
                f"{pkg}: {name} 转发 kind 错配——上游是 {want}，门面转发成 {got}；{why}")

    for name in sorted(declared):
        if name not in up_symbols and name not in up_generics:
            problems.append(
                f"{pkg}: 幽灵转发 {name}——上游已没有这个导出符号（陈旧转发）")

    return problems


def run_local(facade_dir: Path, root: Path, org: str) -> tuple[list[str], int]:
    problems: list[str] = []
    checked = 0
    for pkg, alias_src in facade_packages(facade_dir):
        m = _ALIAS_IMPORT_RE.search(alias_src)
        if not m:
            problems.append(f"{pkg}: alias.go 没有 upstream import，无法判定")
            continue
        repo, pkg_path = upstream_target(m.group("path"), org)
        up_dir = root / repo / pkg_path if pkg_path else root / repo
        if not up_dir.is_dir():
            problems.append(f"{pkg}: 上游包目录不存在（{up_dir}），判不了")
            continue
        up_symbols, up_generics = scan_dir(up_dir)
        declared = facade_declared(alias_src)
        problems += check_package(pkg, up_symbols, up_generics, declared)
        checked += 1
    return problems, checked


def run_remote(org: str, facade_repo: str) -> tuple[list[str], int]:
    problems: list[str] = []
    checked = 0
    pkgs = facade_packages_remote(org, facade_repo)
    if pkgs is None:
        return [f"取不到门面仓 {org}/{facade_repo} 的 alias.go，判不了"], 0
    for pkg, alias_src in pkgs:
        m = _ALIAS_IMPORT_RE.search(alias_src)
        if not m:
            problems.append(f"{pkg}: alias.go 没有 upstream import，无法判定")
            continue
        repo, pkg_path = upstream_target(m.group("path"), org)
        up_symbols, up_generics = scan_remote(org, repo, pkg_path)
        if not up_symbols:
            problems.append(f"{pkg}: 取不到上游 {repo}/{pkg_path} 的源码，判不了")
            continue
        declared = facade_declared(alias_src)
        problems += check_package(pkg, up_symbols, up_generics, declared)
        checked += 1
    return problems, checked


# ---------------------------------------------------------------- 自测

def selftest() -> int:
    """oracle 有效性自测：拿一个**有盲区的被检对象**跑一遍，确认它报得出。

    这不是形式检查——如果 oracle 自己也有同一处盲区，它会对着坏对象说「没问题」，
    那门禁就是假通过。所以自测里故意造三处问题，逐一断言它被抓到。
    """
    failures: list[str] = []

    def check(name: str, got: bool, want: bool) -> None:
        if got != want:
            failures.append(f"{name}: got={got} want={want}")

    with tempfile.TemporaryDirectory() as td:
        root = Path(td) / "root"
        facade = Path(td) / "facade"
        (root / "up" / "pkg").mkdir(parents=True)
        (facade / "pkg").mkdir(parents=True)

        # 上游：3 个导出符号（1 func / 1 const / 1 type）+ 1 个泛型函数
        (root / "up" / "pkg" / "a.go").write_text(
            "package pkg\n\n"
            "const Bar = 1\n\n"
            "type Baz struct{}\n\n"
            "func Foo() {}\n\n"
            "func Gen[T any](v T) T { return v }\n",
            encoding="utf-8")
        # 门面：只转发 Foo；漏 Bar / Baz；幽灵 Qux；泛型函数 Gen 被错误转发
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            "\tQux = upstream.Qux\n"
            ")\n",
            encoding="utf-8")

        up_symbols, up_generics = scan_dir(root / "up" / "pkg")
        declared = facade_declared((facade / "pkg" / "alias.go").read_text(encoding="utf-8"))
        problems = check_package("pkg", up_symbols, up_generics, declared)
        joined = "\n".join(problems)

        check("上游符号提取：Bar 认成 const",
              up_symbols.get("Bar") == "const", True)
        check("上游符号提取：Baz 认成 type",
              up_symbols.get("Baz") == "type", True)
        check("上游符号提取：Foo 认成 func",
              up_symbols.get("Foo") == "func", True)
        check("泛型函数识别：Gen",
              "Gen" in up_generics, True)
        check("漏转发被报出：Bar", "漏转发上游导出符号 Bar" in joined, True)
        check("漏转发被报出：Baz", "漏转发上游导出符号 Baz" in joined, True)
        check("幽灵转发被报出：Qux", "幽灵转发 Qux" in joined, True)
        check("未转发泛型函数不报漏转发", "漏转发上游导出符号 Gen" in joined, False)
        check("const 降级成 var 被报出", "kind 错配" in joined, False)

        # 第二组：把 Bar 转发进 var 块 → 必须报 kind 错配
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            "\tBar = upstream.Bar\n"
            ")\n",
            encoding="utf-8")
        declared = facade_declared((facade / "pkg" / "alias.go").read_text(encoding="utf-8"))
        problems = check_package("pkg", up_symbols, up_generics, declared)
        joined = "\n".join(problems)
        check("const 转发成 var 被报出错配", "Bar 转发 kind 错配" in joined, True)

        # 第三组：type 转发成 var 也必须报出
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tBaz = upstream.Baz\n"
            ")\n",
            encoding="utf-8")
        declared = facade_declared((facade / "pkg" / "alias.go").read_text(encoding="utf-8"))
        problems = check_package("pkg", up_symbols, up_generics, declared)
        check("type 转发成 var 被报出错配",
              "Baz 转发 kind 错配" in "\n".join(problems), True)

        # 第四组：泛型函数被转发 → 必须报出（Go 不允许）
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tGen = upstream.Gen\n"
            ")\n",
            encoding="utf-8")
        declared = facade_declared((facade / "pkg" / "alias.go").read_text(encoding="utf-8"))
        problems = check_package("pkg", up_symbols, up_generics, declared)
        check("泛型函数被转发被报出",
              "泛型函数 Gen 被转发了" in "\n".join(problems), True)

    if failures:
        print("❌ 自测失败：")
        for f in failures:
            print(f"   - {f}")
        return 1
    print("✅ 自测通过：漏转发 / 幽灵转发 / const 降级 / type 降级 / 泛型函数误转发 全部能被报出")
    return 0


# ---------------------------------------------------------------- 入口

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--facade", help="门面仓路径（agentkit 仓根）")
    ap.add_argument("--facade-repo", default="agentkit", help="联网模式下的门面仓名（默认 agentkit）")
    ap.add_argument("--root", help="本地各仓父目录（含 agentkit 门面仓）")
    ap.add_argument("--org", help="联网模式：GitHub 组织名，如 oagentkit")
    ap.add_argument("--json", action="store_true", help="机器可读输出")
    ap.add_argument("--selftest", action="store_true", help="只跑 oracle 有效性自测")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    org = args.org or "oagentkit"

    if args.root:
        if not args.facade:
            print("本地模式必须给 --facade（门面仓路径）", file=sys.stderr)
            return 2
        facade_dir = Path(args.facade).resolve()
        if not facade_dir.is_dir():
            print(f"门面仓路径不存在：{facade_dir}", file=sys.stderr)
            return 2
        root = Path(args.root).resolve()
        problems, checked = run_local(facade_dir, root, org)
        mode = f"local root={root}"
    elif args.org:
        problems, checked = run_remote(args.org, args.facade_repo)
        mode = f"remote org={args.org} facade={args.facade_repo}"
    else:
        print("必须给 --root（本地各仓父目录）或 --org（联网读）", file=sys.stderr)
        return 2

    if args.json:
        print(json.dumps({
            "mode": mode,
            "checked_packages": checked,
            "problems": problems,
        }, ensure_ascii=False, indent=2))
        return 1 if problems else 0

    if not problems:
        print(f"✅ 门面符号级转发完整（{mode}，核对 {checked} 个包）")
        return 0

    print(f"❌ 门面符号级转发不完整（{mode}，核对 {checked} 个包）：")
    for p in problems:
        print(f"   - {p}")
    print()
    print("修法：")
    print("  1) 漏转发 → 在对应门的 alias.go 里补上别名")
    print("     type 上游 → type 块；const 上游 → const 块；func/var 上游 → var 块")
    print("  2) kind 错配 → 把该条目从 var 块挪到 type/const 块")
    print("  3) 幽灵转发 → 删掉该别名（上游已无此符号）")
    print("  4) 泛型函数 → 不要转发，让下游直接引用上游")
    return 1


if __name__ == "__main__":
    sys.exit(main())
