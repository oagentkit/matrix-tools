#!/usr/bin/env python3
"""门面的**符号级**转发完整性校验（独立 oracle）。

## 为什么要有这条守卫

门面仓 `oagentkit/agentkit` 把各模块仓的包做别名转发，让下游**只需改 import 前缀、
无需改调用点**。已有的三条门面守卫查的都不是符号级：

| 守卫 | 查什么 | 查不到什么 |
|---|---|---|
| `verify_facade_packages.py` | 包名（47/47 通过） | 包内的**符号** |
| `check_facade_imports.py` | 禁用的 import 前缀 | 转发内容 |
| `verify_facade_release.py` | 版本地板 | 转发内容 |

实测 2026-10-20（本守卫落地前）：47 个门面包里，**3 个包漏转发 23 个上游导出符号**，
**另有 131 处上游 `const` 被门面转发成 `var`**。

- 漏转发 → 下游按门面 import 直接编译失败（`undefined: Rule` / `undefined: Tokens`）。
- const 降级成 var → 下游把常量用在**常量位置**时编译失败
  （`const x = policy.OpToolCall` 报 "is not constant"；数组长度等常量位置同理）。

  ⚠️ 常见误解：以为 `switch op { case policy.OpToolCall: }` 会挂——**不会**。
  Go 规范里 expression switch 的 case 表达式**不必是常量**（只有 type switch
  的 case 必须是类型）。实测（2026-10-20）：把 const 降级成 var 后，
  `switch op.Type { case policy.OpToolCall: }` 照样编译通过。
  真正挂的是 const 表达式、常量数组长度这些位置。

而 47 个 `alias.go` 的头部都写着 `// Code generated by gen. DO NOT EDIT.`——
**但 `gen` 这个生成器在仓库里根本不存在**。这行声明让人以为有生成器兜底、不会漂移，
实际这些文件是手工冻结的产物（已在 agentkit 仓一并改成实话）。
**本守卫就是那个"生成器"该做但没做的事**——它不生成任何东西，只对账。

## 门面已废弃，但这条守卫必须继续跑

门面仓 `oagentkit/agentkit` 已废弃（v1.x 退役条件**已满足**，
README：「本仓不接受任何新功能，只做别名转发与安全修复」）。
本守卫**不因此停跑**：门面的 alias.go 是**存量下游唯一编译得过的那张脸**——
下游按 `github.com/oagentkit/agentkit/<包>` import 时，符号对不上就是直接构建断裂
（下面「漏转发」「const 降级成 var」两类实测形态）。
废弃说的是「不再接受新功能」，不是「已转发的符号可以烂掉」。

门面的「不得再长出新包」由另一条守卫守：`verify_facade_frozen.py`（冻结基线快照）——
它守的是**包集合**有没有变宽，本守卫守的是**已冻结的那张脸**有没有长歪。两者不重叠。

## 判据

对门面的每个包（47 个）：

1. **不漏**：上游包导出的每个符号，门面都要有对应别名
2. **不错配**：上游是 `type` / `const` 的，门面必须用 `type` / `const` 块转发
   （上游是 `func` 的用 `var` 块转发是**正常**的——Go 允许 `var F = pkg.F`，
   调用点无差别；只有 type/const 降级成 var 才会破坏下游用法）
3. **不幽灵**：门面不得转发上游已不存在的符号（那是陈旧转发，指向已退役的 API）
4. **泛型函数豁免**：Go 的泛型**函数**不能用变量别名转发（`var F = pkg.F[T]` 不合法），
   上游的导出泛型函数必须**不转发**、并登记进显式白名单；
   泛型**类型**可以用泛型类型别名转发（`type G[T any] = upstream.G[T]`，Go 1.24+ 合法），
   **不豁免、必须转发**——把两者混为一谈会把可转发的泛型类型误报成缺失
5. **文档一致**：门面包文档里声明的泛型函数豁免清单，必须等于该包上游实际的泛型函数集合
   （文档是门面对下游的公开承诺，漂了就等于下游不知道该直接引上游）
6. **路径一致**：门面的 upstream import 路径必须等于矩阵登记的 importPath
   （否则门禁会拿「错误的包」当上游来对账，对齐得再准也没意义）

## 独立 oracle：为什么判据不复用被检对象的逻辑

这条门禁**不比对任何生成物**——它直接读**上游源码**与**门面 alias.go**，
两边的符号集都由 `scripts/symdump/main.go`（go/parser 解析语法树）独立提取。

⚠️ 提取方式的坑（2026-10-20 实测，**别再踩**）：

- `go doc -all` **会漏符号**：块内 const 与部分 type 抓不到，
  对 textutil 只报出 19 个真实缺失符号，漏掉 4 个。
- 正则直扫源文件也**不可靠**：`var ( A, B = 1, 2 )` 这类同名多声明按行抓只能拿到 A；
  复合字面量里的缩进字段还可能被误当成声明。

所以提取走 **go/parser**（语法树），声明的完整形态都在节点上。

## 泛型函数白名单

`GENERIC_FUNC_WHITELIST` 是**显式列举**的，不是「跳过所有泛型函数」：

- 上游新增泛型函数而白名单里没有 → **红**（必须有人决定它怎么转发）
- 白名单里的符号已经不是泛型函数了 → **红**（白名单过期，掩盖真实状态）
- 白名单里的泛型函数被门面转发了 → **红**（Go 不允许 `var F = pkg.F[T]`）

## 用法

    verify_facade_symbols.py --root <各仓父目录> --facade <门面仓路径>
    verify_facade_symbols.py --org oagentkit
    verify_facade_symbols.py --root ... --facade ... --json
    verify_facade_symbols.py --selftest

退出码: 0 = 符号级完整；1 = 有缺失/错配/幽灵转发/白名单漂移；2 = 用法或环境错误。
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import repo_meta  # noqa: E402

SYMDUMP = HERE / "symdump" / "main.go"
DEFAULT_VERSIONS = HERE.parent / "versions.json"

# 上游的**导出泛型函数**白名单：门面无法用变量别名转发它们，
# 下游必须直接 import 上游。门面的包文档里也会列同一份清单。
#
# 显式列举（而不是「跳过所有泛型函数」）是刻意的：上游新增泛型函数时，
# 白名单外的泛型函数即红，强制有人做决定，而不是静默放行。
GENERIC_FUNC_WHITELIST: dict[str, set[str]] = {
    "hotplug": {"NewHolder"},
    "progress": {"NewBus"},
    "reportutil": {"Aggregate"},
}


# ---------------------------------------------------------------- 符号提取

class SymdumpError(RuntimeError):
    """提取器跑不起来（缺 go 工具链 / 解析失败）。**判不了 ≠ 没有**。"""


def run_symdump(manifest: dict) -> dict:
    """跑一次 symdump 批量提取。返回 {"upstream": {...}, "facade": {...}}。"""
    with tempfile.TemporaryDirectory() as td:
        mpath = Path(td) / "manifest.json"
        mpath.write_text(json.dumps(manifest), encoding="utf-8")
        try:
            proc = subprocess.run(
                ["go", "run", str(SYMDUMP), "--manifest", str(mpath)],
                capture_output=True, text=True,
            )
        except OSError as e:
            raise SymdumpError(f"go 工具链不可用: {e}") from e
        if proc.returncode != 0:
            raise SymdumpError(
                f"symdump 执行失败: {proc.stderr.strip()[:400] or proc.stdout.strip()[:400]}")
        try:
            return json.loads(proc.stdout)
        except ValueError as e:
            raise SymdumpError(f"symdump 输出不是合法 JSON: {e}") from e


def matrix_index(versions_path: Path) -> dict[str, dict]:
    """versions.json → {门面包名: {repo, subdir, importPath}}。

    门面的包名 = 矩阵包路径的**末段**（`worker/pglease` → `pglease`、
    `knowledge/rag` → `rag`），门面目录名就是这个末段。
    """
    data = json.loads(versions_path.read_text(encoding="utf-8"))
    out: dict[str, dict] = {}
    for m in data.get("modules", []):
        repo = m["repo"]
        for p in m.get("packages", []):
            leaf = p["pkg"].rstrip("/").split("/")[-1]
            import_path = p.get("importPath", "")
            prefix = f"github.com/{data.get('defaultOrg', 'oagentkit')}/{repo}/"
            subdir = import_path[len(prefix):] if import_path.startswith(prefix) else ""
            out[leaf] = {"repo": repo, "subdir": subdir, "importPath": import_path}
    return out


# ---------------------------------------------------------------- 本地模式

def local_inputs(root: Path, facade_dir: Path, index: dict) -> tuple[list, list, list]:
    """构造 symdump 的 manifest（本地模式）。→ (manifest, 门面元信息, 问题)

    # 枚举基准：门面**实际转发**的包，不是矩阵的全部包

    这条门禁的立论是「**已冻结的那张脸**有没有长歪」——门面转发了什么，就核对什么。
    枚举基准若取「矩阵的全部包」，矩阵每新增一个包，这条门禁就要求门面跟着长一张新脸；
    而门面早已废弃（「不接受任何新功能，只做别名转发」），**矩阵新增包时门面不该跟**。

    两条门禁各管一面、互不重叠：
    - 本门禁（符号级）：门面**已经转发**的包，符号集是否与上游对得上；
    - `verify_facade_frozen.py`（包级）：门面的**实际包集合**是否 ⊆ 冻结基线，
      即「门面有没有长出新包」。门面若多转发了 `toolfail`，冻结门禁会报红。

    所以「门面没转发某个矩阵包」**不是这条门禁的问题**——那是正常状态，不是缺陷。
    把它报红会让矩阵每次新增包都撞红，而修法（给门面补转发）恰恰是门面不该做的事。

    漏转发怎么仍然被抓住：门面的 alias.go 若转发了一个上游**已不存在的符号**，
    那是「幽灵转发」，由 `check_package` 报红；门面的 alias.go 若**漏了上游的某个符号**，
    那是「漏转发」，同样由 `check_package` 报红——两者都发生在「门面确实转发了的包」上，
    与枚举基准无关。
    """
    manifest = {"upstream": [], "facade": []}
    facade_meta = []
    problems: list[str] = []
    # 门面实际转发的包：门面仓下一层含 alias.go 的目录。
    facade_pkgs = sorted(
        child.name for child in facade_dir.iterdir()
        if child.is_dir() and not child.name.startswith(".")
        and (child / "alias.go").is_file()
    )
    for pkg in facade_pkgs:
        info = index.get(pkg)
        if info is None:
            # 门面转发的包不在矩阵登记里：矩阵漏登记，由幽灵包门禁负责；
            # 本门禁无从核对上游（拿不到 importPath），跳过而不误报。
            problems.append(f"{pkg}: 门面转发了它，但矩阵未登记该包（判不了上游符号）")
            continue
        up_dir = root / info["repo"] / info["subdir"] if info["subdir"] else root / info["repo"]
        alias = facade_dir / pkg / "alias.go"
        if not up_dir.is_dir():
            problems.append(f"{pkg}: 上游包目录不存在（{up_dir}），判不了")
            continue
        manifest["upstream"].append({"key": pkg, "dir": str(up_dir.resolve())})
        manifest["facade"].append({"key": pkg, "file": str(alias.resolve())})
        facade_meta.append(pkg)
    return manifest, facade_meta, problems


# ---------------------------------------------------------------- 联网模式

def remote_inputs(org: str, facade_repo: str, index: dict) -> tuple[list, list, list, str | None]:
    """构造 symdump 的 manifest（联网模式）。

    先把各仓的源码快照（tarball）拉到临时目录，再**复用本地模式那套检查逻辑**——
    联网与本地只有「源码从哪来」不同，判据不该有两份实现（两份实现迟早分叉，
    分叉出来的就是盲区）。

    → (manifest, 门面元信息, 问题, 临时目录)
    """
    tmpdir = tempfile.mkdtemp(prefix="facade-syms-")
    root = Path(tmpdir)
    problems: list[str] = []

    repos = {info["repo"] for info in index.values()}
    repos.add(facade_repo)
    for repo in sorted(repos):
        if repo_meta.fetch_repo_snapshot(org, repo, root) is None:
            problems.append(f"取不到 {org}/{repo} 的源码快照，判不了")
    if problems:
        return {"upstream": [], "facade": []}, [], problems, tmpdir

    manifest, facade_meta, local_problems = local_inputs(
        root, root / facade_repo, index)
    return manifest, facade_meta, local_problems, tmpdir


# ---------------------------------------------------------------- 判定

def check_package(pkg: str, up: dict, fa: dict, matrix_import: str) -> list[str]:
    """单个门面包的问题描述列表（空 = 符号级完整）。

    up: {符号名: {"kind": ..., "generic": bool}}
    fa: {"upstream": 路径, "declared": {名: 转发kind}, "localDefs": [...], "docGenerics": [...]}
    """
    problems: list[str] = []
    declared = fa.get("declared", {})

    # 6. 门面转发到的上游包必须与矩阵登记的一致
    if fa.get("upstream") and matrix_import and fa["upstream"] != matrix_import:
        problems.append(
            f"{pkg}: 门面的 upstream import 是 {fa['upstream']}，"
            f"矩阵登记的 importPath 是 {matrix_import}——对账对象错了，"
            f"先修门面的转发路径")

    whitelist = GENERIC_FUNC_WHITELIST.get(pkg, set())
    up_generic_funcs = {n for n, s in up.items()
                        if s["kind"] == "func" and s.get("generic")}

    for name in sorted(up):
        sym = up[name]
        if sym["kind"] == "func" and sym.get("generic"):
            # 4. 泛型函数
            if name in declared:
                problems.append(
                    f"{pkg}: 泛型函数 {name} 被转发了——Go 不允许 `var F = pkg.F[T]`，"
                    f"必须删掉这条转发并让下游直接引用上游")
            if name not in whitelist:
                problems.append(
                    f"{pkg}: 上游新增泛型函数 {name}，未登记进 GENERIC_FUNC_WHITELIST——"
                    f"必须显式决定它怎么处理（泛型函数无法用变量别名转发）")
            continue
        if name not in declared:
            problems.append(
                f"{pkg}: 漏转发上游导出符号 {name}（上游 kind={sym['kind']}）")
            continue
        want, got = sym["kind"], declared[name]
        if want in ("type", "const") and got != want:
            if want == "type":
                why = ("type 被降级成 var 后门面自己就编译不过"
                       "（var 块里不能赋一个类型）")
            else:
                why = ("const 被降级成 var 后，下游把它用在**常量位置**会编译不过"
                       "（const 声明、数组长度等要求常量）"
                       "——注意：expression switch 的 case 不受此影响，"
                       "Go 规范允许 case 表达式不是常量")
            problems.append(
                f"{pkg}: {name} 转发 kind 错配——上游是 {want}，门面转发成 {got}；{why}")

    for name in sorted(declared):
        if name not in up:
            problems.append(
                f"{pkg}: 幽灵转发 {name}——上游已没有这个导出符号（陈旧转发）")

    # 4b. 白名单过期：登记为泛型函数的符号，上游已不是泛型函数了
    for name in sorted(whitelist):
        if name not in up_generic_funcs:
            problems.append(
                f"{pkg}: 白名单里的 {name} 在上游已经不是泛型函数——"
                f"白名单过期会掩盖真实状态，请同步更新 GENERIC_FUNC_WHITELIST")

    # 5. 文档里的泛型函数豁免清单必须与上游实际一致
    doc = set(fa.get("docGenerics") or [])
    if doc != up_generic_funcs:
        problems.append(
            f"{pkg}: 包文档声明的泛型函数豁免是 {sorted(doc) or '（无）'}，"
            f"上游实际的泛型函数是 {sorted(up_generic_funcs) or '（无）'}——"
            f"文档是门面对下游的公开承诺，漂了下游就不知道该直接引上游")

    # 门面是纯转发层：出现自研定义说明它不再是纯 re-export
    for name in sorted(fa.get("localDefs") or []):
        problems.append(
            f"{pkg}: 门面里出现了非转发定义 {name}——门面应当是纯 re-export 层，"
            f"自研逻辑请放回上游模块仓")

    return problems


# ---------------------------------------------------------------- 自测

def selftest() -> int:
    """oracle 有效性自测：拿一个**有盲区的被检对象**跑一遍，确认它报得出。

    这不是形式检查——如果 oracle 自己也有同一处盲区，它会对着坏对象说「没问题」，
    那门禁就是假通过。所以自测里故意造六类缺陷，逐一断言它被抓到。
    """
    failures: list[str] = []

    def check(name: str, got: bool, want: bool) -> None:
        if got != want:
            failures.append(f"{name}: got={got} want={want}")

    with tempfile.TemporaryDirectory() as td:
        root = Path(td) / "root"
        facade = Path(td) / "facade"
        (root / "up" / "pkg").mkdir(parents=True)
        (facade / "pkg").mkdir(parents=True)

        # 上游：1 func / 1 const / 1 type / 1 泛型函数 / 1 泛型类型
        (root / "up" / "pkg" / "a.go").write_text(
            "package pkg\n\n"
            "const Bar = 1\n\n"
            "type Baz struct{}\n\n"
            "type Gen[T any] struct{ V T }\n\n"
            "func Foo() {}\n\n"
            "func GenFn[T any](v T) T { return v }\n",
            encoding="utf-8")
        # 门面：只转发 Foo；漏 Bar / Baz / Gen；幽灵 Qux；泛型函数 GenFn 被错误转发
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            "\tQux = upstream.Qux\n"
            "\tGenFn = upstream.GenFn\n"
            ")\n",
            encoding="utf-8")

        manifest = {
            "upstream": [{"key": "pkg", "dir": str(root / "up" / "pkg")}],
            "facade": [{"key": "pkg", "file": str(facade / "pkg" / "alias.go")}],
        }
        out = run_symdump(manifest)
        up = out["upstream"]["pkg"]["symbols"]
        fa = out["facade"]["pkg"]

        check("上游符号提取：Bar 认成 const", up.get("Bar", {}).get("kind") == "const", True)
        check("上游符号提取：Baz 认成 type", up.get("Baz", {}).get("kind") == "type", True)
        check("上游符号提取：Foo 认成 func", up.get("Foo", {}).get("kind") == "func", True)
        check("上游符号提取：泛型类型 Gen 被标 generic",
              up.get("Gen", {}).get("generic") is True, True)
        check("上游符号提取：泛型函数 GenFn 被标 generic",
              up.get("GenFn", {}).get("generic") is True, True)
        check("上游符号提取：非泛型符号不带 generic",
              up.get("Foo", {}).get("generic") is False, True)

        problems = check_package("pkg", up, fa, "github.com/up/pkg")
        joined = "\n".join(problems)
        check("漏转发被报出：Bar", "漏转发上游导出符号 Bar" in joined, True)
        check("漏转发被报出：Baz", "漏转发上游导出符号 Baz" in joined, True)
        check("幽灵转发被报出：Qux", "幽灵转发 Qux" in joined, True)
        check("泛型函数被转发被报出", "泛型函数 GenFn 被转发了" in joined, True)
        check("白名单外的泛型函数被报出", "未登记进 GENERIC_FUNC_WHITELIST" in joined, True)
        check("泛型类型 Gen 被报成缺失（泛型类型必须转发，不豁免）",
              "漏转发上游导出符号 Gen" in joined, True)
        check("泛型函数 GenFn 未被误报成缺失",
              "漏转发上游导出符号 GenFn" in joined, False)

        # 第二组：const 转发进 var 块 → 必须报 kind 错配
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            "\tBar = upstream.Bar\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        problems = check_package("pkg", up, fa, "github.com/up/pkg")
        check("const 转发成 var 被报出错配",
              "Bar 转发 kind 错配" in "\n".join(problems), True)

        # 第三组：type 转发成 var 也必须报出
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tBaz = upstream.Baz\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        check("type 转发成 var 被报出错配",
              "Baz 转发 kind 错配" in "\n".join(check_package("pkg", up, fa, "github.com/up/pkg")),
              True)

        # 第四组：泛型类型必须用 type 块转发（var 块转发泛型类型 = 下游用不了）
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tGen = upstream.Gen\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        check("泛型类型转发成 var 被报出错配",
              "Gen 转发 kind 错配" in "\n".join(check_package("pkg", up, fa, "github.com/up/pkg")),
              True)

        # 第五组：完整转发（泛型类型用 type 块）→ 不该报「不漏/错配/幽灵」
        (facade / "pkg" / "alias.go").write_text(
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "type (\n"
            "\tBaz = upstream.Baz\n"
            "\tGen[T any] = upstream.Gen[T]\n"
            ")\n\n"
            "const (\n"
            "\tBar = upstream.Bar\n"
            ")\n\n"
            "var (\n"
            "\tFoo = upstream.Foo\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        problems = check_package("pkg", up, fa, "github.com/up/pkg")
        check("完整转发不报不漏/错配/幽灵",
              not any(("漏转发" in p or "kind 错配" in p or "幽灵转发" in p) for p in problems),
              True)

        # 第七组：文档里的泛型函数清单与上游实际不一致 → 必须报出
        (facade / "pkg" / "alias.go").write_text(
            "// Package pkg 是兼容门面。\n"
            "//\n"
            "// 注意：泛型函数无法用变量别名转发，这些符号请直接引用上游：GenFn\n"
            "package pkg\n\n"
            'import upstream "github.com/up/pkg"\n\n'
            "var (\n"
            "\tFoo = upstream.Foo\n"
            ")\n",
            encoding="utf-8")
        out = run_symdump(manifest)
        fa = out["facade"]["pkg"]
        check("文档泛型清单被解析出来", fa.get("docGenerics") == ["GenFn"], True)

        # 第八组：白名单**命中**与**过期**两条路径
        #
        # 这两条必须分开测：白名单命中时（上游确有该泛型函数、门面也没转发）
        # 不该报错；白名单过期时（上游已没有那个泛型函数）必须报错。
        # 只测一条的话，另一条坏了门禁照样绿。
        for pkg_name, upstream_src, want_stale in (
            ("hotplug", "func NewHolder[T any](v T) T { return v }\n", False),
            ("progress", "func Plain() {}\n", True),
        ):
            up_dir = root / "wl" / pkg_name
            up_dir.mkdir(parents=True, exist_ok=True)
            (up_dir / "a.go").write_text(
                f"package {pkg_name}\n\n" + upstream_src, encoding="utf-8")
            fa_dir = facade / pkg_name
            fa_dir.mkdir(parents=True, exist_ok=True)
            (fa_dir / "alias.go").write_text(
                f"package {pkg_name}\n\n"
                f'import upstream "github.com/up/{pkg_name}"\n\n'
                "var (\n"
                "\tPlain = upstream.Plain\n"
                ")\n",
                encoding="utf-8")
            wl_manifest = {
                "upstream": [{"key": pkg_name, "dir": str(up_dir)}],
                "facade": [{"key": pkg_name, "file": str(fa_dir / "alias.go")}],
            }
            wl_out = run_symdump(wl_manifest)
            wl_problems = check_package(
                pkg_name, wl_out["upstream"][pkg_name]["symbols"],
                wl_out["facade"][pkg_name], f"github.com/up/{pkg_name}")
            wl_joined = "\n".join(wl_problems)
            if want_stale:
                check(f"白名单过期（{pkg_name}）被报出",
                      "白名单过期" in wl_joined, True)
            else:
                check(f"白名单命中（{pkg_name}）不报过期",
                      "白名单过期" in wl_joined, False)
                check(f"白名单命中（{pkg_name}）不报未登记",
                      "未登记进 GENERIC_FUNC_WHITELIST" in wl_joined, False)
                check(f"白名单命中（{pkg_name}）的泛型函数不算漏转发",
                      "漏转发" in wl_joined, False)

    if failures:
        print("❌ 自测失败：")
        for f in failures:
            print(f"   - {f}")
        return 1
    print("✅ 自测通过：漏转发 / 幽灵转发 / const 降级 / type 降级 / 泛型函数误转发 / "
          "泛型函数未登记白名单 / 白名单过期 / 泛型类型不误报 全部能被报出")
    return 0


# ---------------------------------------------------------------- 入口

def main() -> int:
    ap = argparse.ArgumentParser(description="校验门面的符号级 re-export 完整性")
    ap.add_argument("--facade", help="门面仓路径（agentkit 仓根）")
    ap.add_argument("--facade-repo", default="agentkit",
                    help="联网模式下的门面仓名（默认 agentkit）")
    ap.add_argument("--root", help="本地各仓父目录（含 agentkit 门面仓）")
    ap.add_argument("--org", help="联网模式：GitHub 组织名，如 oagentkit")
    ap.add_argument("--versions", default=str(DEFAULT_VERSIONS),
                    help="矩阵真相源 versions.json（提供 importPath 交叉校验）")
    ap.add_argument("--json", action="store_true", help="机器可读输出")
    ap.add_argument("--selftest", action="store_true", help="只跑 oracle 有效性自测")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    versions_path = Path(args.versions)
    if not versions_path.is_file():
        print(f"❌ 找不到矩阵文件: {versions_path}", file=sys.stderr)
        return 2
    index = matrix_index(versions_path)
    if not index:
        print(f"❌ {versions_path} 里没有可用的包清单", file=sys.stderr)
        return 2

    problems: list[str] = []
    checked = 0
    tmpdir = None
    if args.root:
        if not args.facade:
            print("本地模式必须给 --facade（门面仓路径）", file=sys.stderr)
            return 2
        facade_dir = Path(args.facade).resolve()
        root = Path(args.root).resolve()
        if not facade_dir.is_dir():
            print(f"❌ 门面仓路径不存在：{facade_dir}", file=sys.stderr)
            return 2
        manifest, facade_meta, problems = local_inputs(root, facade_dir, index)
        mode = f"local root={root} facade={facade_dir}"
    elif args.org:
        manifest, facade_meta, problems, tmpdir = remote_inputs(
            args.org, args.facade_repo, index)
        mode = f"remote org={args.org} facade={args.facade_repo}"
    else:
        print("必须给 --root（本地各仓父目录）或 --org（联网读）", file=sys.stderr)
        return 2

    try:
        out = run_symdump(manifest)
    except SymdumpError as e:
        print(f"❌ 符号提取失败（判不了，不能当成「没问题」）：{e}", file=sys.stderr)
        return 1
    finally:
        if tmpdir:
            import shutil
            shutil.rmtree(tmpdir, ignore_errors=True)

    for pkg in facade_meta:
        up = out["upstream"].get(pkg, {})
        fa = out["facade"].get(pkg, {})
        if up.get("error"):
            problems.append(f"{pkg}: 上游符号提取失败：{up['error']}")
            continue
        if fa.get("error"):
            problems.append(f"{pkg}: 门面 alias.go 解析失败：{fa['error']}")
            continue
        problems += check_package(pkg, up.get("symbols", {}), fa,
                                  index[pkg]["importPath"])
        checked += 1

    if checked == 0:
        # 一个包都没查到 = 取数层坏了，不是「一致」。
        # 必须把取数层报的原因一并打出来，否则只看到「没检查到」，
        # 排查的人会以为是判据写错，而真因（API 取不到 / 路径不对）在上面。
        print("❌ 一个门面包都没检查到（拒绝判定）", file=sys.stderr)
        for p in problems:
            print(f"   - {p}", file=sys.stderr)
        if not problems:
            print("   （取数层没有报出具体原因——检查 matrix 的 importPath 与仓库布局是否对得上）",
                  file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps({
            "mode": mode,
            "checked_packages": checked,
            "problems": problems,
        }, ensure_ascii=False, indent=2))
        return 1 if problems else 0

    if not problems:
        print(f"✅ 门面符号级转发完整（{mode}，核对 {checked} 个包）")
        return 0

    print(f"❌ 门面符号级转发不完整（{mode}，核对 {checked} 个包）：")
    for p in problems:
        print(f"   - {p}")
    print()
    print("修法：")
    print("  1) 漏转发 → 在对应门的 alias.go 里补上别名")
    print("     type 上游 → type 块；const 上游 → const 块；func/var 上游 → var 块")
    print("  2) kind 错配 → 把该条目从 var 块挪到 type/const 块")
    print("  3) 幽灵转发 → 删掉该别名（上游已无此符号）")
    print("  4) 泛型函数 → 不要转发，让下游直接引用上游；并登记进 GENERIC_FUNC_WHITELIST")
    print("  5) 文档清单 → 与上游实际泛型函数保持一致")
    return 1


if __name__ == "__main__":
    sys.exit(main())
